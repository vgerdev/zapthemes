package com.zapthemes.tools;

import java.io.IOException;
import java.lang.reflect.Constructor;
import java.lang.reflect.GenericArrayType;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.lang.reflect.ParameterizedType;
import java.lang.reflect.Type;
import java.lang.reflect.TypeVariable;
import java.lang.reflect.WildcardType;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.Comparator;
import java.util.List;
import java.util.stream.Collectors;
import java.util.stream.Stream;

import org.eclipse.swt.widgets.Display;
import org.eclipse.swt.widgets.Widget;

/**
 * Generates one proxy source file per widget class: a public subclass in the {@code com.zapthemes}
 * package tree with the same simple name and every public constructor of the original. Each
 * constructor calls {@code super(...)} and then {@code ThemeManager.applyOnCreate(this, "<Name>")}.
 *
 * <pre>
 * ProxyGenerator --list proxies.txt --out build/generated/sources/proxies/java [--skip-existing src/main/java]
 * </pre>
 * A proxy that already has a hand-written source under {@code --skip-existing} is not generated
 * (it is still listed in the index class).
 */
public final class ProxyGenerator {

    private ProxyGenerator() {
    }

    public static void main(String[] args) throws Exception {
        Path list = null;
        Path out = null;
        Path handWritten = null;
        for (int i = 0; i < args.length; i++) {
            switch (args[i]) {
                case "--list" -> list = Path.of(args[++i]);
                case "--out" -> out = Path.of(args[++i]);
                case "--skip-existing" -> handWritten = Path.of(args[++i]);
                default -> throw new IllegalArgumentException("Unknown argument: " + args[i]);
            }
        }
        if (list == null || out == null) {
            throw new IllegalArgumentException("Usage: ProxyGenerator --list <file> --out <dir>");
        }
        clean(out);
        ClassLoader loader = ProxyGenerator.class.getClassLoader();
        List<String> names = ProxyNames.readList(list);
        List<String> proxies = new ArrayList<>();
        for (String name : names) {
            Class<?> original = Class.forName(name, false, loader);
            String proxy = ProxyNames.proxyOf(name);
            proxies.add(proxy);
            if (handWritten != null && Files.exists(handWritten.resolve(proxy.replace('.', '/') + ".java"))) {
                continue;
            }
            write(out, proxy, generate(original, proxy));
        }
        var index = ProxyNames.indexClass(list);
        if (index.isPresent()) {
            write(out, index.get(), generateIndex(index.get(), proxies));
        }
        System.out.println("Generated " + names.size() + " proxies into " + out);
    }

    private static void write(Path out, String className, String source) throws IOException {
        Path file = out.resolve(className.replace('.', '/') + ".java");
        Files.createDirectories(file.getParent());
        Files.writeString(file, source);
    }

    /** A class with {@code ALL}: every generated proxy class, in proxy-list order. */
    static String generateIndex(String indexClass, List<String> proxies) {
        int dot = indexClass.lastIndexOf('.');
        StringBuilder src = new StringBuilder();
        src.append("// Generated by ").append(ProxyGenerator.class.getName()).append(". Do not edit.\n");
        src.append("package ").append(indexClass, 0, dot).append(";\n\n");
        src.append("/** Every generated proxy class, in proxy-list order. */\n");
        src.append("public final class ").append(indexClass.substring(dot + 1)).append(" {\n\n");
        src.append("    public static final java.util.List<Class<? extends org.eclipse.swt.widgets.Widget>> ALL = java.util.List.of(");
        for (int i = 0; i < proxies.size(); i++) {
            src.append(i == 0 ? "\n" : ",\n").append("            ").append(proxies.get(i)).append(".class");
        }
        src.append(");\n\n");
        src.append("    private ").append(indexClass.substring(dot + 1)).append("() {\n    }\n}\n");
        return src.toString();
    }

    /** The source of the proxy class {@code proxyName} for {@code original}. */
    public static String generate(Class<?> original, String proxyName) {
        if (!Widget.class.isAssignableFrom(original)) {
            throw new IllegalArgumentException(original.getName() + " is not an SWT Widget");
        }
        int modifiers = original.getModifiers();
        if (!Modifier.isPublic(modifiers) || Modifier.isAbstract(modifiers) || Modifier.isFinal(modifiers)) {
            throw new IllegalArgumentException(original.getName() + " must be public, concrete and non-final");
        }
        int dot = proxyName.lastIndexOf('.');
        String packageName = proxyName.substring(0, dot);
        String simpleName = proxyName.substring(dot + 1);
        if (!simpleName.equals(original.getSimpleName())) {
            throw new IllegalArgumentException("A proxy keeps the simple name: " + proxyName);
        }

        StringBuilder src = new StringBuilder();
        src.append("// Generated by ").append(ProxyGenerator.class.getName())
                .append(" from ").append(original.getName()).append(". Do not edit.\n");
        src.append("package ").append(packageName).append(";\n\n");
        src.append("/**\n");
        src.append(" * Theme-aware {@link ").append(original.getName()).append("}: tags itself with\n");
        src.append(" * {@code THEME_CONTROL_TYPE = \"").append(simpleName)
                .append("\"} and applies the current theme on creation.\n");
        src.append(" */\n");
        String typeParameters = typeParameters(original);
        String typeArguments = typeParameters.isEmpty() ? ""
                : Stream.of(original.getTypeParameters()).map(TypeVariable::getName).collect(Collectors.joining(", ", "<", ">"));
        src.append("public class ").append(simpleName).append(typeParameters)
                .append(" extends ").append(original.getCanonicalName()).append(typeArguments).append(" {\n");

        List<Constructor<?>> constructors = new ArrayList<>(Arrays.asList(original.getConstructors()));
        constructors.sort(Comparator.<Constructor<?>>comparingInt(Constructor::getParameterCount)
                .thenComparing(c -> Arrays.toString(c.getParameterTypes())));
        for (Constructor<?> constructor : constructors) {
            appendConstructor(src, original, simpleName, constructor);
        }

        if (!checkSubclassIsFinal(original)) {
            src.append("\n    @Override\n");
            src.append("    protected void checkSubclass() {\n");
            src.append("        // SWT rejects subclasses by default; a proxy only adds theming.\n");
            src.append("    }\n");
        }
        src.append("}\n");
        return src.toString();
    }

    private static void appendConstructor(StringBuilder src, Class<?> original, String simpleName, Constructor<?> constructor) {
        Class<?>[] types = constructor.getParameterTypes();
        Type[] genericTypes = constructor.getGenericParameterTypes();
        List<String> names = parameterNames(types);
        String typeList = Stream.of(types).map(Class::getCanonicalName).reduce((a, b) -> a + ", " + b).orElse("");

        src.append("\n    /** @see ").append(original.getName()).append("#").append(original.getSimpleName())
                .append("(").append(typeList).append(") */\n");
        // Theming inside the constructor is the point of a proxy (see ThemeManager.applyOnCreate).
        if (constructor.isAnnotationPresent(Deprecated.class)) {
            src.append("    @Deprecated\n");
            src.append("    @SuppressWarnings({\"deprecation\", \"this-escape\"})\n");
        } else {
            src.append("    @SuppressWarnings(\"this-escape\")\n");
        }
        src.append("    public ").append(simpleName).append("(");
        for (int i = 0; i < types.length; i++) {
            if (i > 0) {
                src.append(", ");
            }
            Type type = genericTypes.length == types.length ? genericTypes[i] : types[i];
            String name = typeName(type);
            if (constructor.isVarArgs() && i == types.length - 1) {
                name = name.substring(0, name.length() - 2) + "...";
            }
            src.append(name).append(' ').append(names.get(i));
        }
        src.append(")");
        Type[] exceptions = constructor.getGenericExceptionTypes();
        if (exceptions.length > 0) {
            src.append(" throws ").append(Stream.of(exceptions).map(ProxyGenerator::typeName).collect(Collectors.joining(", ")));
        }
        src.append(" {\n");
        src.append("        super(").append(String.join(", ", names)).append(");\n");
        src.append("        com.zapthemes.core.ThemeManager.applyOnCreate(this, \"").append(simpleName).append("\");\n");
        src.append("    }\n");
    }

    /** {@code <T extends Foo>} for generic widgets such as Nebula's {@code Tiles<T>}; empty otherwise. */
    static String typeParameters(Class<?> type) {
        TypeVariable<?>[] variables = type.getTypeParameters();
        if (variables.length == 0) {
            return "";
        }
        return Stream.of(variables).map(variable -> {
            List<String> bounds = Stream.of(variable.getBounds())
                    .filter(bound -> bound != Object.class)
                    .map(ProxyGenerator::typeName)
                    .toList();
            return bounds.isEmpty() ? variable.getName() : variable.getName() + " extends " + String.join(" & ", bounds);
        }).collect(Collectors.joining(", ", "<", ">"));
    }

    /** Java source spelling of a (possibly generic) type. */
    static String typeName(Type type) {
        return switch (type) {
            case Class<?> c -> c.getCanonicalName();
            case ParameterizedType p -> typeName(p.getRawType())
                    + Stream.of(p.getActualTypeArguments()).map(ProxyGenerator::typeName).collect(Collectors.joining(", ", "<", ">"));
            case GenericArrayType a -> typeName(a.getGenericComponentType()) + "[]";
            case WildcardType w -> w.getLowerBounds().length > 0 ? "? super " + typeName(w.getLowerBounds()[0])
                    : w.getUpperBounds().length > 0 && w.getUpperBounds()[0] != Object.class ? "? extends " + typeName(w.getUpperBounds()[0])
                    : "?";
            case TypeVariable<?> v -> v.getName();
            default -> type.getTypeName();
        };
    }

    /** A widget library may forbid overriding {@code checkSubclass}; then the proxy must not. */
    static boolean checkSubclassIsFinal(Class<?> type) {
        for (Class<?> k = type; k != null && k != Widget.class; k = k.getSuperclass()) {
            try {
                Method method = k.getDeclaredMethod("checkSubclass");
                return Modifier.isFinal(method.getModifiers());
            } catch (NoSuchMethodException e) {
                // Not declared here; look further up.
            }
        }
        return false;
    }

    /** Readable names, as SWT is not compiled with {@code -parameters}. */
    static List<String> parameterNames(Class<?>[] types) {
        List<String> names = new ArrayList<>();
        int ints = 0;
        for (Class<?> type : types) {
            String name;
            if (type == Display.class) {
                name = "display";
            } else if (Widget.class.isAssignableFrom(type) && !names.contains("parent")) {
                name = "parent";
            } else if (type == int.class) {
                name = switch (ints++) {
                    case 0 -> "style";
                    case 1 -> "index";
                    default -> "arg" + names.size();
                };
            } else {
                name = "arg" + names.size();
            }
            names.add(name);
        }
        return names;
    }

    private static void clean(Path dir) throws IOException {
        if (Files.isDirectory(dir)) {
            try (Stream<Path> paths = Files.walk(dir)) {
                for (Path path : paths.sorted(Comparator.reverseOrder()).toList()) {
                    Files.delete(path);
                }
            }
        }
        Files.createDirectories(dir);
    }
}
